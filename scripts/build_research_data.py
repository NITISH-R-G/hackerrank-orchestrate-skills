"""Build the verified Orchestrate research dataset from committed raw snapshots.

    python scripts/build_research_data.py            # rebuild data/ and docs/ tables
    python scripts/build_research_data.py --check    # fail if committed outputs are stale

Inputs (all committed, all reproducible):
  data/sources.json          source list: URL, retrieval date, access status
  data/raw/*.csv             leaderboard snapshots with NO participant names or handles
  data/country-observations.json  search observations recorded by hand, each with a timestamp

Outputs:
  data/orchestrate-research.json
  data/country-query-matrix.json
  docs/COUNTRY_VISIBILITY.md   generated from the matrix; never edited by hand

Nothing here infers a participant's country from location data. A country is
only attached when a public source names it.
"""

from __future__ import annotations

import csv
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
DOCS = ROOT / "docs"
SECTIONS = ["chat_10", "interview_30", "output_csv_30", "code_zip_30"]
MAX = {"chat_10": 10, "interview_30": 30, "output_csv_30": 30, "code_zip_30": 30}


def read_json(name: str):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def leaderboard_stats(path: Path) -> dict:
    rows = list(csv.DictReader(path.open(encoding="utf-8")))
    stats = {"rows": len(rows), "sections": {}, "final": {}}
    for col in SECTIONS:
        vals = [float(r[col]) for r in rows]
        stats["sections"][col] = {
            "min": min(vals), "max": max(vals),
            "mean": round(statistics.mean(vals), 2),
            "sd": round(statistics.pstdev(vals), 2),
            "section_max": MAX[col],
        }
    finals = [float(r["final_100"]) for r in rows]
    sums_ok = all(abs(sum(float(r[c]) for c in SECTIONS) - float(r["final_100"])) < 0.05 for r in rows)
    stats["final"] = {"min": min(finals), "max": max(finals), "sum_check_all_rows": sums_ok}
    return stats


def build_research(sources: dict) -> dict:
    snapshots = {}
    for path in sorted((DATA / "raw").glob("*.csv")):
        snapshots[path.name] = {"path": f"data/raw/{path.name}", **leaderboard_stats(path)}
    return {
        "generated_by": "scripts/build_research_data.py",
        "schema_version": 1,
        "editions": read_json("editions.json"),
        "sources": sources["sources"],
        "leaderboard_snapshots": snapshots,
        "country_coverage": {
            "publicly_named_countries": [],
            "aggregate_claims": [
                {
                    "claim": "12,885 people registered for the first Orchestrate edition (May 1) from 48 countries",
                    "source_id": "hackerrank-blog-behind-the-scenes-2026-06-08",
                    "type": "aggregate_count",
                }
            ],
            "note": "No public page names the countries of participants. Leaderboard pages do not show country. Contest pages are login-gated.",
        },
        "rejected_records": [],
        "failures": [],
    }


def build_matrix(observations: dict) -> dict:
    countries = observations["countries"]
    queries = observations["queries"]
    seen = set()
    records = []
    for obs in observations["observations"]:
        key = (obs["country_code"], obs["query_id"], obs["provider"])
        if key in seen:
            raise ValueError(f"duplicate observation {key}")
        seen.add(key)
        records.append(obs)
    return {
        "generated_by": "scripts/build_research_data.py",
        "method": "Logged-out Google web search, pws=0, num=20. Country set by gl= parameter (a hint, not a real location). Single browser tab.",
        "countries": countries,
        "queries": queries,
        "observations": records,
        "summary": summarise(countries, queries, records),
    }


def summarise(countries, queries, records) -> dict:
    total = len(countries) * len(queries)
    by_status: dict[str, int] = {}
    for r in records:
        by_status[r["status"]] = by_status.get(r["status"], 0) + 1
    untested = total - len(records)
    first = sum(1 for r in records if r["status"] == "first")
    return {
        "country_query_pairs_planned": total,
        "observed": len(records),
        "untested": untested,
        "first_place": first,
        "by_status": by_status,
    }


def render_visibility(matrix: dict) -> str:
    s = matrix["summary"]
    lines = [
        "# Country visibility",
        "",
        "Generated by `scripts/build_research_data.py` from `data/country-query-matrix.json`. Do not edit by hand.",
        "",
        f"- Country and query pairs planned: {s['country_query_pairs_planned']}",
        f"- Observed: {s['observed']}",
        f"- Not tested: {s['untested']}",
        f"- Repository in first place: {s['first_place']}",
        "",
        "| Country | Code | Query | Provider | Observed on | Position | Status | Limitation |",
        "|---|---|---|---|---|---|---|---|",
    ]
    names = {c["code"]: c["name"] for c in matrix["countries"]}
    for r in matrix["observations"]:
        lines.append(
            f"| {names.get(r['country_code'], r['country_code'])} | {r['country_code']} | {r['query_id']} | "
            f"{r['provider']} | {r['observed_at']} | {r['position'] or '-'} | {r['status']} | {r['limitation']} |"
        )
    untested = [c for c in matrix["countries"] if not any(o["country_code"] == c["code"] for o in matrix["observations"])]
    lines += ["", "## Countries with no observation", ""]
    lines += [f"- {c['name']} ({c['code']})" for c in untested] or ["- none"]
    return "\n".join(lines) + "\n"


def main() -> int:
    check = "--check" in sys.argv
    sources = read_json("sources.json")
    observations = read_json("country-observations.json")
    research = build_research(sources)
    matrix = build_matrix(observations)
    visibility = render_visibility(matrix)

    outputs = {
        DATA / "orchestrate-research.json": json.dumps(research, indent=2, ensure_ascii=False) + "\n",
        DATA / "country-query-matrix.json": json.dumps(matrix, indent=2, ensure_ascii=False) + "\n",
        DOCS / "COUNTRY_VISIBILITY.md": visibility,
    }
    if check:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("STALE:", ", ".join(stale))
            return 1
        print("all generated outputs are up to date")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
