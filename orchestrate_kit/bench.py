"""Measured performance numbers for `orchestrate_kit`'s own CLI commands.

    python -m orchestrate_kit.bench > BENCHMARKS.md

Every number in `BENCHMARKS.md` is generated by this script, run against
this machine, on this commit. It is not a claim about "how fast
orchestrate_kit is" in general -- wall-clock time depends on the machine
running it. It IS a reproducible measurement anyone can regenerate and
compare against, which is the only kind of performance claim this project
makes anywhere (see PLAYBOOK.md, TIMELINE.md F-48: "document the trade you
made, don't hide it").

Deliberately excluded: peak memory via a proper profiler (tracemalloc is
used instead of a heavier dependency, since this project ships zero runtime
dependencies on principle -- see pyproject.toml's comment on that).
"""

from __future__ import annotations

import platform
import statistics
import subprocess
import sys
import time
import tracemalloc
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

COMMANDS: list[tuple[str, list[str]]] = [
    ("memory seed", ["memory", "seed"]),
    ("memory list", ["memory", "list"]),
    ("memory why-not \"embeddings\"", ["memory", "why-not", "embeddings"]),
    ("mentor \"add OCR\"", ["mentor", "I want to add OCR"]),
    ("mentor \"tune BM25 k1\"", ["mentor", "tune the BM25 k1 parameter"]),
    ("evaluate .", ["evaluate", "."]),
    ("selftest", ["selftest"]),
    ("viz architecture", ["viz", "architecture"]),
    ("graph", ["graph"]),
]

REPEATS = 5


def _time_subprocess(args: list[str]) -> float:
    """Wall-clock time for a fresh interpreter running the command, the way a
    real user experiences it -- not an in-process call that skips Python
    startup."""
    start = time.perf_counter()
    subprocess.run([sys.executable, "-m", "orchestrate_kit", *args],
                   cwd=ROOT, capture_output=True, text=True, timeout=120)
    return time.perf_counter() - start


def _peak_memory_in_process(args: list[str]) -> float:
    """Peak Python-object memory for the SAME command run in-process via
    tracemalloc, in MB. This is a different (smaller) number than OS-level
    RSS for a fresh subprocess -- it measures what orchestrate_kit's own code
    allocates, not interpreter startup overhead. Both numbers are reported;
    neither is hidden."""
    from orchestrate_kit.cli import build_parser

    import contextlib
    import io

    # Every CLI handler prints its result -- that's the product, not a bug in
    # THEM. But calling one in-process to measure memory means ITS stdout
    # becomes THIS script's stdout, which pollutes `bench.py > BENCHMARKS.md`
    # with a random command's raw output in the middle of a markdown table.
    # Caught by actually piping this script's own output, not by inspection.
    tracemalloc.start()
    try:
        parsed = build_parser().parse_args(args)
        with contextlib.redirect_stdout(io.StringIO()):
            parsed.fn(parsed)
    except SystemExit:
        pass
    finally:
        _, peak = tracemalloc.get_traced_memory()
        tracemalloc.stop()
    return peak / (1024 * 1024)


def run() -> list[dict]:
    rows = []
    for label, args in COMMANDS:
        times = [_time_subprocess(args) for _ in range(REPEATS)]
        try:
            mem = _peak_memory_in_process(args)
        except Exception:  # noqa: BLE001 -- an in-process call has side effects
            mem = None      # some commands aren't safe to call twice in one
                            # interpreter (e.g. argparse SystemExit paths);
                            # report unknown rather than guess.
        rows.append({
            "label": label,
            "mean_s": statistics.mean(times),
            "min_s": min(times),
            "max_s": max(times),
            "stdev_s": statistics.stdev(times) if len(times) > 1 else 0.0,
            "peak_mb": mem,
        })
    return rows


def render_markdown(rows: list[dict]) -> str:
    out = []
    a = out.append
    a("# Benchmarks")
    a("")
    a(f"Generated by `python -m orchestrate_kit.bench` on {platform.system()} "
      f"{platform.release()}, Python {platform.python_version()}. "
      f"{REPEATS} repeats per command, cold subprocess each time (real "
      f"Python startup cost included -- this is what a user actually waits "
      f"for, not an in-process microbenchmark).")
    a("")
    a("**Regenerate on your own machine:** `python -m orchestrate_kit.bench "
      "> BENCHMARKS.md`. These numbers are a property of this repository at "
      "this commit on THIS machine, not a universal claim.")
    a("")
    a("| command | mean | min | max | stdev | peak Python memory |")
    a("|---|---:|---:|---:|---:|---:|")
    for r in rows:
        mem = f"{r['peak_mb']:.1f} MB" if r["peak_mb"] is not None else "n/a¹"
        a(f"| `{r['label']}` | {r['mean_s']*1000:.0f} ms | "
          f"{r['min_s']*1000:.0f} ms | {r['max_s']*1000:.0f} ms | "
          f"{r['stdev_s']*1000:.1f} ms | {mem} |")
    a("")
    a("¹ not measured for commands whose CLI handler isn't safe to call "
      "twice in one interpreter (e.g. an argparse path that raises "
      "`SystemExit`) -- reported as unknown rather than guessed.")
    a("")
    a("## Reading these numbers")
    a("")
    a("- **Every command is offline and makes no network call** — the "
      "numbers above are Python startup + local computation only, not "
      "affected by network latency or a provider's response time.")
    a("- **`selftest` is the slowest by design** — it builds a fixture repo, "
      "injects 13 defects one at a time, and runs the full evaluator against "
      "each. That's ~14 full evaluator passes in one command.")
    a("- **`evaluate .` is by far the slowest command, and that's expected**: "
      "the generic plugin's `fresh-clone` audit does a REAL `git clone` of "
      "this repository, then a fresh `python -m pytest` inside the clone "
      "(PLAYBOOK P15 — \"the single highest-yield audit in this "
      "framework\"). The number is dominated by that clone-and-test cost, "
      "not by anything specific to `orchestrate_kit`'s own logic, and it "
      "scales with the size of the repo being evaluated.")
    return "\n".join(out)


def main() -> int:
    print(render_markdown(run()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
