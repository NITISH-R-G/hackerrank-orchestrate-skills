"""Plugin scaffolding.

    orchestrate plugin new rag --detect "eval/questions.jsonl"

Generates a working plugin AND the negative control for it, in one step,
because a plugin shipped without a negative control is a plugin nobody can
trust. The generated audit deliberately FAILS out of the box on the fixture it
also generates: your first run should be red, and making it green is the
exercise.

Three things the template enforces by construction, all of them mistakes this
project has already made and recorded:

  detect on SHAPE, never on a repo name       (works for any season/fork)
  never raise -- a crash is reported          (a crashed audit is not a pass)
  never pass silently when it cannot run      (skipped is UNKNOWN, not OK)
"""

