    def detect(self, ctx: RepoContext) -> bool:
        """Detect on SHAPE, never on a repository name.

        A name check works exactly once -- for your repo, this season. A shape
        check works for every fork, rename and future edition.
        """
        return ctx.exists("{detect}")
