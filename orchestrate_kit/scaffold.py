README = """# `{name}` plugin

{title}

## Register it

```python
from {module} import {cls}Plugin

evaluator.register({cls}Plugin())
```

## Detection

Keys on `{detect}`. **Shape, not name** — so it applies to any fork or future
edition of the same problem, and never to a repo that merely shares a title.

## Before you open a PR

- [ ] `test_the_audit_can_actually_fail` passes with a REAL injected defect,
      not the placeholder
- [ ] the `xfail` marker on `test_healthy_repo_is_clean` is removed
- [ ] every audit sets `res.skipped` with a reason when it cannot run
- [ ] every `Finding` carries literal evidence — command output or a file
      excerpt, not a paraphrase
- [ ] no audit writes to the repository it is auditing

That last one has bitten this project: a benchmark invoked a CLI without an
output flag and silently overwrote the submission artifact three times per run.
"""


def new_plugin(name: str, detect: str, category: str, dest: Path,
               title: str = "") -> list[Path]:
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    mod = slug.replace("-", "_")
    cls = "".join(part.capitalize() for part in re.split(r"[-_]", slug))
    title = title or f"{slug.replace('-', ' ').title()} audits"

    pkg = dest / mod
    pkg.mkdir(parents=True, exist_ok=True)
    fields = dict(name=slug, cls=cls, title=title, detect=detect,
                  category=category, module=mod,
                  parent=str(Path(detect).parent).replace("\\", "/"))

    written = []
    for path, body in (
        (pkg / "__init__.py", PLUGIN.format(**fields)),
        (pkg / f"test_{mod}_plugin.py", TEST.format(**fields)),
        (pkg / "README.md", README.format(**fields)),
    ):
        path.write_text(body, encoding="utf-8")
        written.append(path)
    return written
